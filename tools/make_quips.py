"""Builds lib/evolve/quips_data.h from docs/achievements.md,
so the silly achievements are edited in one place: the list.

usage: python -I tools/make_quips.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "achievements.md")
OUT = os.path.join(ROOT, "lib", "evolve", "quips_data.h")

POOLS = ["Round one", "Stage 1", "Stage 2", "Stage 3", "Stage 4", "Stage 5"]
EVENTS = ["First meal of another cell", "Crowned in round one", "Reaching stage 2", "Reaching stage 3",
          "Reaching stage 4", "Reaching stage 5", "Your first bop of a rival", "First time evolving is paused",
          "100th meal"]


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    pools, events, cur = {p: [] for p in POOLS}, {}, None
    for line in open(SRC, encoding="utf-8"):
        line = line.rstrip()
        if line.startswith("### "):
            cur = next((p for p in POOLS if line[4:].startswith(p)), None)
            if line[4:].startswith("Event lines"):
                cur = "events"
            continue
        if not line.startswith("- "):
            continue
        item = line[2:]
        if cur == "events":
            m = re.match(r"\*\*(.+?):\*\* (.+)", item)
            if m:
                events[m.group(1)] = m.group(2)
        elif cur:
            pools[cur].append(item)
    missing = [e for e in EVENTS if e not in events]
    if missing:
        raise SystemExit(f"event lines missing from the list: {missing}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/make_quips.py from docs/achievements.md. Edit the list, not this.\n")
        f.write("#pragma once\n\n")
        for i, p in enumerate(POOLS):
            f.write(f"static const char* const pool{i}[] = {{\n")
            for q in pools[p]:
                f.write(f"    {c_str(q)},\n")
            f.write("};\n")
        f.write("static const char* const* const pools[] = {" + ", ".join(f"pool{i}" for i in range(len(POOLS))) + "};\n")
        f.write("static const int poolSizes[] = {" + ", ".join(
            f"sizeof pool{i} / sizeof pool{i}[0]" for i in range(len(POOLS))) + "};\n")
        f.write("static const char* const events[] = {\n")
        for e in EVENTS:
            f.write(f"    {c_str(events[e])},\n")
        f.write("};\n")
    print(f"{OUT}: " + ", ".join(f"{p} {len(pools[p])}" for p in POOLS) + f", {len(EVENTS)} events")


if __name__ == "__main__":
    main()
