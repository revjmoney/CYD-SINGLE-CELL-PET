"""Builds the silly achievement data from the lists, so the lines are edited in one place:

  python -I tools/make_quips.py          docs/achievements.md      -> lib/evolve/quips_data.h       (Cell Pet)
  python -I tools/make_quips.py --duck   docs/achievements-duck.md -> lib/evolve/quips_duck_data.h  (Duck Pet)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVENTS = ["First meal of another cell", "Crowned in round one", "Reaching stage 2", "Reaching stage 3",
          "Reaching stage 4", "Reaching stage 5", "Your first bop of a rival", "First time evolving is paused",
          "100th meal"]
BOOKS = {
    "cell": dict(src="achievements.md", out="quips_data.h",
                 pools=["Round one", "Stage 1", "Stage 2", "Stage 3", "Stage 4", "Stage 5"], events=EVENTS),
    "duck": dict(src="achievements-duck.md", out="quips_duck_data.h",
                 pools=["Round one", "Stage 1", "Stage 2", "Stage 3", "Stage 4", "Stage 5", "Villain"],
                 events=["First meal of another duck"] + EVENTS[1:] + ["Beat an evil duckling", "First frog",
                                                                      "First goldfish"]),
}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(name):
    b = BOOKS[name]
    src = os.path.join(ROOT, "docs", b["src"])
    out = os.path.join(ROOT, "lib", "evolve", b["out"])
    pools, events, cur = {p: [] for p in b["pools"]}, {}, None
    for line in open(src, encoding="utf-8"):
        line = line.rstrip()
        if line.startswith("### "):
            cur = next((p for p in b["pools"] if line[4:].startswith(p)), None)
            if line[4:].startswith("Event lines"):
                cur = "events"
            continue
        if not line.startswith("- "):
            continue
        item = line[2:]
        if cur == "events":
            m = re.match(r"\*\*(.+?):\*\* (.+)", item)
            if m:
                events[m.group(1)] = m.group(2)
        elif cur:
            pools[cur].append(item)
    missing = [e for e in b["events"] if e not in events]
    if missing:
        raise SystemExit(f"event lines missing from {b['src']}: {missing}")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"// Generated by tools/make_quips.py from docs/{b['src']}. Edit the list, not this.\n")
        f.write("#pragma once\n\n")
        for i, p in enumerate(b["pools"]):
            f.write(f"static const char* const {name}_pool{i}[] = {{\n")
            for q in pools[p]:
                f.write(f"    {c_str(q)},\n")
            f.write("};\n")
        n = len(b["pools"])
        f.write(f"static const char* const* const {name}_pools[] = {{" + ", ".join(f"{name}_pool{i}" for i in range(n)) + "};\n")
        f.write(f"static const int {name}_sizes[] = {{" + ", ".join(
            f"sizeof {name}_pool{i} / sizeof {name}_pool{i}[0]" for i in range(n)) + "};\n")
        f.write(f"static const char* const {name}_events[] = {{\n")
        for e in b["events"]:
            f.write(f"    {c_str(events[e])},\n")
        f.write("};\n")
    print(f"{out}: " + ", ".join(f"{p} {len(pools[p])}" for p in b["pools"]) + f", {len(b['events'])} events")


if __name__ == "__main__":
    build("duck" if "--duck" in sys.argv else "cell")
